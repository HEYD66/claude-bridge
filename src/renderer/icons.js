/** 输入框右上角的像素小螃蟹（装饰） */
export function crab(size = 34) {
  const rows = ['..XXXXXXXX..', '..XXXXXXXX..', '..XOXXXXOX..', 'XXXXXXXXXXXX', 'XXXXXXXXXXXX', '..XXXXXXXX..', '..X.X..X.X..', '..X.X..X.X..'];
  const cells = [];
  rows.forEach((row, y) =>
    [...row].forEach((c, x) => {
      if (c === 'X') cells.push(`<rect x="${x}" y="${y}" width="1.02" height="1.02"/>`);
      else if (c === 'O') cells.push(`<rect class="eye" x="${x}" y="${y}" width="1.02" height="1.02"/>`);
    }),
  );
  return `<svg class="crab" width="${size}" height="${Math.round((size * 8) / 12)}" viewBox="0 0 12 8" shape-rendering="crispEdges" aria-hidden="true"><g fill="currentColor">${cells.join('')}</g></svg>`;
}

